/** 取某观察点的五档判据；未收录时返回 null（调用方跳过，不阻断评分）。 */
export function pointBands(code: string): PointBands | null {
  return POINT_BAND_NOTES[code] ?? null;
}

/** 生成注入 prompt 的多行判据片段；无该点数据时返回空串。 */
export function pointBandPromptLines(code: string, indent = '  '): string {
  const b = pointBands(code);
  if (!b) return '';
  return POINT_BAND_ORDER.map((k) => `${indent}${POINT_BAND_LABEL[k]}：${b[k]}`).join('\n');
}
