export type GradeBand = 'primary' | 'junior' | 'senior';
export type LessonTypeCode = 'new' | 'review' | 'comment' | 'practice' | 'topic';

export interface LessonTypePoint {
  /** 全局唯一编码：`{课型}-{视角序}-{要点序}`，如 new-2-3 */
  code: string;
  /** 手册原始要点编号（个别课型存在跳号，按手册原样保留） */
  no: number;
  name: string;
  /** 手册给出的判定定义（原文） */
  definition: string;
}

export interface LessonTypeViewpoint {
  /** 全局唯一编码：`{课型}-{视角序}`，如 new-2 */
  code: string;
  name: string;
  points: LessonTypePoint[];
}

export interface LessonTypeModel {
  code: LessonTypeCode;
  name: string;
  /** 手册小节号 */
  manual_section: string;
  summary: string;
  /** 手册「主要学习活动」词表，按学段区分（用于课型自动识别） */
  activities: Record<GradeBand, string[]>;
  viewpoints: LessonTypeViewpoint[];
}

